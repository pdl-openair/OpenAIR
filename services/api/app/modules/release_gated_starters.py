def _with_contract_metadata(starter: dict[str, Any]) -> dict[str, Any]:
    item = deepcopy(starter)
    item["usageGuide"] = _usage_guide(item)
    sample = VERIFIED_SAMPLE_BY_STARTER_ID.get(item["starterId"])
    if sample:
        item["verifiedSample"] = deepcopy(sample)
        item["sampleStatus"] = "verified"
        item["secondaryAction"] = "查看样例"
    else:
        item["verifiedSample"] = None
        item["sampleStatus"] = "pending"
        item["sampleDisabledReason"] = SAMPLE_DISABLED_REASON
        item.pop("secondaryAction", None)
    return item


def list_public_starters() -> list[dict[str, Any]]:
    return [
        _with_contract_metadata(starter)
        for starter in RELEASE_GATED_STARTERS
        if starter["visibility"] == "public_invited_trial"
        and starter["releaseDecision"] not in {"hidden", "internal_only"}
    ]


def find_starter(starter_id: str) -> dict[str, Any] | None:
    for starter in RELEASE_GATED_STARTERS:
        if starter["starterId"] == starter_id:
            return _with_contract_metadata(starter)
    return None


    guide = USAGE_GUIDE_BY_STARTER_ID.get(starter["starterId"])
    if guide:
        return guide
    return {
        "suitableFor": starter["description"],
        "input": "输入：" + "、".join(starter.get("requiredInputs") or ["一句真实科研问题"]),
        "output": "输出：" + "、".join(starter.get("outputList") or ["任务草案"]),
        "boundary": starter.get("boundaryCopy") or starter.get("trustBoundary") or "当前结果需要人工复核后再使用。",
    }


